import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createFarCull } from './farCull.ts';

const scene = new THREE.Scene();
const world = new THREE.Group(); world.name = 'world-test'; scene.add(world);
const props = new THREE.Group(); props.name = 'props'; world.add(props);
const terrain = new THREE.Mesh(new THREE.PlaneGeometry(2000, 2000)); world.add(terrain);
const box = () => new THREE.Mesh(new THREE.BoxGeometry(2, 2, 2));
const near = box(); near.position.set(100, 0, 0); props.add(near);
const far = box(); far.position.set(400, 0, 0); props.add(far);
const big = new THREE.Mesh(new THREE.BoxGeometry(800, 2, 2)); big.position.set(500, 0, 0); props.add(big);
const hiddenByOther = box(); hiddenByOther.position.set(50, 0, 0); hiddenByOther.visible = false; props.add(hiddenByOther);
const tank = box(); tank.position.set(900, 0, 0); scene.add(tank);
scene.updateMatrixWorld(true);
const cam = new THREE.PerspectiveCamera(); cam.position.set(0, 0, 0); cam.updateMatrixWorld();

const cull = createFarCull(250, 0);
cull.update(scene, cam, 1, true);
assert.equal(near.visible, true, 'near prop stays');
assert.equal(far.visible, false, 'prop at 400 m hidden');
assert.equal(big.visible, true, 'prop whose edge reaches 250 m stays');
assert.equal(tank.visible, true, 'tanks are never culled');
assert.equal(terrain.visible, true, 'terrain is never culled');
assert.equal(hiddenByOther.visible, false, 'objects hidden by others stay hidden');
cam.position.set(300, 0, 0); cam.updateMatrixWorld();
cull.update(scene, cam, 2, true);
assert.equal(far.visible, true, 'prop returns when the camera comes close');
cam.position.set(0, 0, 0); cam.updateMatrixWorld();
cull.update(scene, cam, 3, true);
assert.equal(far.visible, false);
cull.update(scene, cam, 4, false);
assert.equal(far.visible, true, 'preset off restores everything it hid');
assert.equal(hiddenByOther.visible, false, 'preset off never shows what others hid');
console.log('farCull.selftest: far props hidden, tanks/terrain/others untouched, restore on off passed');
